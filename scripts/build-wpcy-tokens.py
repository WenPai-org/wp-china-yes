#!/usr/bin/env python3
"""Generate src/Admin/app/tokens.css (--wpcy-*) from the pinned kit tokens.json.

Usage:
  python3 scripts/build-wpcy-tokens.py           # write tokens.css
  python3 scripts/build-wpcy-tokens.py --check   # exit 1 if tokens.css is stale

Adapted from wenpai-admin-ui scripts/build-tokens.py (--target wpcy).
Machine source of truth remains kit tokens/tokens.json; this repo vendors a
pinned copy at src/Admin/app/design-tokens/tokens.json (still --wenpai-* shape).
Standard library only. Never scope tokens to :root.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "Admin" / "app" / "design-tokens" / "tokens.json"
OUT = ROOT / "src" / "Admin" / "app" / "tokens.css"
REF = re.compile(r"\{([a-z0-9-]+)\.([a-z0-9-]*)\}")

WENPAI_PREFIX = "--wenpai-"
PREFIX_TO = "--wpcy-"
DEFAULT_SCOPE = ".wpcy-app"
SCOPE_KEY = "wpcy_scope"  # optional override in tokens.json
LABEL = "wp-china-yes Admin"


def load() -> dict:
    return json.loads(SRC.read_text(encoding="utf-8"))


def remap_group_prefix(prefix: str) -> str:
    if not prefix.startswith(WENPAI_PREFIX):
        raise SystemExit(
            f"unexpected group prefix {prefix!r}; expected startswith {WENPAI_PREFIX!r}"
        )
    return PREFIX_TO + prefix[len(WENPAI_PREFIX) :]


def var_name(groups: dict, group: str, key: str) -> str:
    return remap_group_prefix(groups[group]["prefix"]) + key


def resolve(value: str, groups: dict) -> str:
    def sub(m: re.Match) -> str:
        g, k = m.group(1), m.group(2)
        if g not in groups or k not in groups[g]["tokens"]:
            raise SystemExit(f"unknown token reference {m.group(0)}")
        return f"var({var_name(groups, g, k)})"

    return REF.sub(sub, value)


def render(data: dict) -> str:
    groups = data["groups"]
    scope = data.get(SCOPE_KEY) or DEFAULT_SCOPE
    if scope.strip() == ":root":
        raise SystemExit("tokens must not be scoped to :root")
    lines = [
        f"/* {LABEL} design tokens. GENERATED by scripts/build-wpcy-tokens.py",
        " * from src/Admin/app/design-tokens/tokens.json (pinned kit consumer copy).",
        " * Do not edit by hand; run the script. Machine source of truth:",
        " * wenpai-admin-ui tokens/tokens.json — bump kit first, then refresh the pin.",
        f" * Scoped to {scope} (never the document root).",
        f" * Target: wpcy (prefix {PREFIX_TO}*).",
    ]
    bps = data.get("breakpoints", {}).get("values", {})
    if bps:
        lines.append(" * Breakpoints (media queries cannot read custom properties):")
        for name, bp in bps.items():
            lines.append(f" *   {name}: {bp['value']}")
    lines.append(" */")
    lines.append("")
    lines.append(scope + " {")
    seen: set[str] = set()
    first = True
    for gname, group in groups.items():
        if not first:
            lines.append("")
        first = False
        lines.append(f"  /* {gname} */")
        for key, tok in group["tokens"].items():
            name = var_name(groups, gname, key)
            if name in seen:
                raise SystemExit(f"duplicate custom property {name}")
            seen.add(name)
            lines.append(f"  {name}: {resolve(str(tok['value']), groups)};")
    lines.append("}")
    # Kit PHP body.wenpai-ui-page extras stay kit-only (same as --target wpcy).
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="fail if src/Admin/app/tokens.css is stale",
    )
    args = ap.parse_args()
    if not SRC.is_file():
        print(f"FAIL tokens: missing {SRC.relative_to(ROOT)}", file=sys.stderr)
        return 1
    css = render(load())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != css:
            print(
                "FAIL tokens: src/Admin/app/tokens.css is stale; "
                "run python3 scripts/build-wpcy-tokens.py",
                file=sys.stderr,
            )
            return 1
        print("PASS tokens: src/Admin/app/tokens.css matches design-tokens/tokens.json")
        return 0
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
